"""Generic prompt-lookup drafts, always verified by the original greedy model.

No dataset IDs, target answers or external draft model are used. Only a suffix
already generated by this request may propose a continuation from its prompt.
Unmatched proposals are discarded; unaccepted KV is truncated before reuse.
"""
from __future__ import annotations


def prompt_draft(prompt: list[int], generated: list[int], limit: int) -> list[int]:
    if limit < 1:
        return []
    for width in range(min(4, len(generated)), 1, -1):
        suffix = generated[-width:]
        for pos in range(len(prompt) - width, -1, -1):
            if prompt[pos:pos + width] == suffix:
                proposal = prompt[pos + width:pos + width + limit]
                if proposal:
                    return proposal
    return []


def verified_count(draft: list[int], predictions: list[int]) -> int:
    """Retain the original model's mismatch token or its all-match bonus token."""
    if len(predictions) != len(draft) + 1:
        raise ValueError("verification needs one target prediction per draft plus a bonus")
    for index, token in enumerate(draft):
        if predictions[index] != token:
            return index + 1
    return len(predictions)


def try_prompt_lookup_step(backend, rows) -> bool:
    import torch
    import torch.nn.functional as F
    from engine.runtime.backend import IM_END, TTS_EOS
    from engine.runtime.backend_s import THINKER_CHUNK
    from engine.server import TextDelta

    drafts = []
    speculative = []
    ordinary = []
    for lv in rows:
        boundary = THINKER_CHUNK + 1 + THINKER_CHUNK * lv.chunk_index
        # Stop at the same text-chunk boundary as the ordinary scheduler.
        limit = min(backend.thinker_prompt_lookup_max_tokens, boundary - len(lv.generated) - 1)
        proposal = prompt_draft(lv.prompt_ids, lv.generated, limit)
        if proposal:
            speculative.append(lv)
            drafts.append(proposal)
        else:
            ordinary.append(lv)
    if not speculative:
        return False
    stats = backend.thinker_prompt_lookup_stats
    if ordinary:
        backend._thinker_step_group(ordinary, _skip_prompt_lookup=True)
    feeds = [[lv.generated[-1], *draft] for lv, draft in zip(speculative, drafts)]
    demands = {lv.seq: len(feed) for lv, feed in zip(speculative, feeds)}
    if not backend.tkv.can_fit(demands):
        stats['kv_fallbacks'] += 1
        backend._thinker_step_group(speculative, _skip_prompt_lookup=True)
        return True
    starts = [backend.tkv.lengths[lv.seq] for lv in speculative]
    layout = backend.tkv.layout([lv.seq for lv in speculative], [len(feed) for feed in feeds])
    tokens = torch.tensor([token for feed in feeds for token in feed], dtype=torch.int64, device=backend.device)
    # Low-concurrency prefix caching disables batched append-prefill in its
    # ordinary lane. Verification is a separate packed suffix workload and
    # explicitly qualifies that existing backend here, with its exact fallback.
    prior_append = backend.trun.batch_append_prefill
    backend.trun.batch_append_prefill = not getattr(backend, 'thinker_lookup_batched_disabled', False)
    try:
        hidden = backend._decoder_forward(backend.trun, backend.thinker.embed(tokens), layout)
    finally:
        if not backend.trun.batch_append_prefill:
            backend.thinker_lookup_batched_disabled = True
        backend.trun.batch_append_prefill = prior_append
    predictions = F.linear(hidden, backend.thinker.w['lm_head.weight']).float().argmax(-1).tolist()
    stats['verification_calls'] += 1
    stats['draft_tokens'] += sum(len(draft) for draft in drafts)
    offset = 0
    for lv, draft, feed, start in zip(speculative, drafts, feeds, starts):
        predicted = predictions[offset:offset + len(feed)]
        keep = verified_count(draft, predicted)
        consumed = 0
        for index in range(keep):
            token = predicted[index]
            lv.hidden.append(hidden[offset + index])
            consumed += 1
            stats['target_tokens'] += 1
            if index < len(draft) and token == draft[index]:
                stats['matched_draft_tokens'] += 1
            if token in (TTS_EOS, IM_END):
                backend._close_thinker(lv)
                break
            lv.generated.append(token)
            lv.emit(TextDelta(backend.tok.decode([token])))
            boundary = THINKER_CHUNK + 1 + THINKER_CHUNK * lv.chunk_index
            if len(lv.generated) == boundary:
                final = lv.chunk_index == -(-lv.req.max_tokens // THINKER_CHUNK) - 1
                backend._pass_chunk(lv, final=final)
                lv.chunk_index += 1
                if final:
                    backend._close_thinker(lv, passed_final=True)
                break
        if not lv.thinker_done:
            backend.tkv.truncate(lv.seq, start + consumed)
        offset += len(feed)
    return True
